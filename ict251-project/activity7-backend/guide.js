// Builds the HTML API guide shown at GET /.

const PROJECT_NAME = process.env.PROJECT_NAME || "Campus Maintenance Requests";
const STUDENT_NUMBER = process.env.STUDENT_NUMBER || "202501509";

function esc(value) {
  return String(value)
    .replace(/&/g, "&amp;").replace(/</g, "&lt;")
    .replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

const ROUTES = [
  ["GET", "/", "Show this API guide."],
  ["GET", "/health", "Check that the server and database respond."],
  ["GET", "/api/records", "Read all records."],
  ["GET", "/api/records/:id", "Read one record."],
  ["POST", "/api/records", "Create a record."],
  ["PUT", "/api/records/:id", "Update a record (replaces all four fields)."],
  ["DELETE", "/api/records/:id", "Delete a record."]
];

const FIELDS = [
  ["id", "Positive whole number", "Generated by the database. Never sent in POST or PUT."],
  ["title", "Text, 3 to 80 characters", "A short name for the request."],
  ["category", "Text, 2 to 40 characters", "For example Electrical, Plumbing, Furniture."],
  ["description", "Text, 5 to 300 characters", "A clear explanation of the fault."],
  ["status", "Pending, In progress or Completed", "Exact values only."]
];

const CODES = [
  ["200", "Read, update or delete succeeded."],
  ["201", "Record created (POST)."],
  ["400", "Invalid input, invalid id or malformed JSON."],
  ["404", "Record or route does not exist."],
  ["500", "Unexpected server failure."],
  ["503", "/health only: the database is not responding."]
];

function table(headers, rows) {
  const head = headers.map(h => `<th>${esc(h)}</th>`).join("");
  const body = rows
    .map(r => `<tr>${r.map(c => `<td>${esc(c)}</td>`).join("")}</tr>`)
    .join("");
  return `<table><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table>`;
}

const SAMPLE_BODY = JSON.stringify({
  title: "Broken classroom light",
  category: "Electrical",
  description: "The light in Room B12 does not switch on.",
  status: "Pending"
}, null, 2);

function guidePage(baseUrl) {
  const b = esc(baseUrl);
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(PROJECT_NAME)} API</title>
<style>
  body { font-family: system-ui, sans-serif; max-width: 52rem; margin: 2rem auto; padding: 0 1rem; line-height: 1.5; color: #1a1a1a; }
  h1 { margin-bottom: .25rem; } h2 { margin-top: 2rem; border-bottom: 1px solid #ccc; padding-bottom: .25rem; }
  table { border-collapse: collapse; width: 100%; margin: .75rem 0; }
  th, td { border: 1px solid #bbb; padding: .4rem .6rem; text-align: left; vertical-align: top; }
  th { background: #f0f0f0; }
  pre, code { background: #f5f5f5; border-radius: 4px; }
  pre { padding: .75rem; overflow-x: auto; } code { padding: 0 .25rem; }
  a { color: #0b5cad; }
</style>
</head>
<body>
<h1>${esc(PROJECT_NAME)} API</h1>
<p><strong>Student number:</strong> ${esc(STUDENT_NUMBER)} &middot; ICT251 Activity 7, Mulungushi University</p>
<p>A JSON API for campus maintenance requests (broken lights, leaking taps, damaged furniture).
All records are made-up demonstration data stored in an SQLite database.</p>

<h2>Base URL</h2>
<p><code>${b}</code></p>
<ul>
  <li><a href="${b}/health">${b}/health</a></li>
  <li><a href="${b}/api/records">${b}/api/records</a></li>
</ul>

<h2>Routes</h2>
${table(["Method", "Route", "Purpose"], ROUTES)}

<h2>Record fields</h2>
${table(["Field", "Rule", "Meaning"], FIELDS)}
<p>Allowed statuses: <code>Pending</code>, <code>In progress</code>, <code>Completed</code>.</p>

<h2>Valid POST and PUT body</h2>
<p>Send <code>Content-Type: application/json</code> with all four editable fields. Do not send <code>id</code>.</p>
<pre>${esc(SAMPLE_BODY)}</pre>

<h2>Status codes</h2>
${table(["Code", "Meaning"], CODES)}
<p>Errors are JSON, for example <code>{"message":"Title must have 3 to 80 characters."}</code>.
A successful DELETE returns <code>{"message":"Record deleted."}</code>.</p>

<p><em>Note: a free hosted service may sleep when idle, so the first request can take up to a minute to start.</em></p>
</body>
</html>`;
}

module.exports = { guidePage };
